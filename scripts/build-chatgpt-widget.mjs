import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
const bundle=await build({entryPoints:['chatgpt-widget/widget.ts'],bundle:true,write:false,minify:true,format:'iife',platform:'browser',target:'es2020',legalComments:'none'})
const script=bundle.outputFiles[0].text.replace(/<\/script/gi,'<\\/script')
const css=await readFile('chatgpt-widget/style.css','utf8')
const template=await readFile('chatgpt-widget/index.html','utf8')
const notices=await readFile('chatgpt-widget/THIRD-PARTY-NOTICES.txt','utf8')
const html=template.replace('/*STYLE*/',css).replace('/*SCRIPT*/',()=>script).replace('</body>',()=>`<!-- ${notices.replace(/-->/g,'-- >')} -->\n</body>`)
const hash=value=>createHash('sha256').update(value).digest('base64')
await writeFile('lib/chatgpt-widget.generated.ts',`// Generated by npm run chatgpt:build. Do not edit.\nexport const widgetHtml = ${JSON.stringify(html)}\nexport const widgetScriptHash = ${JSON.stringify(hash(script))}\nexport const widgetStyleHash = ${JSON.stringify(hash(css))}\n`)
console.log('Built self-contained LegalAIMCP widget (official MCP Apps bridge; no remote assets).')
